def test_operation_is_broadcast_to_other_clients(base: Base, websocket_client):
    """An operation is sent to the other clients in the room, but not back to its sender."""
    table_name = 'test_operation_is_broadcast'
    table, _ = setup_table(base, table_name)
    row_id = new_row_id()

    # Both clients connect after the setup, so that they only receive the operation below
    sender = websocket_client()
    listener = websocket_client()

    execute(sender, {
        'op_type': 'append_rows',
        'table_id': table['_id'],
        'row_datas': [{'_id': row_id, table['columns'][0]['key']: 'broadcast'}],
    })

    event = listener.next_event()

    assert event['op_type'] == 'append_rows'
    assert event['row_datas'][0]['_id'] == row_id

    # The client that sent the operation does not receive it back
    with pytest.raises(queue.Empty):
        sender.events.get(timeout=1)


def test_append_rows(base: Base, websocket: WebSocketClient, snapshot_json: SnapshotAssertion):
    table_name = 'test_append_rows'
    table, _ = setup_table(base, table_name)
    text_key, number_key = (column['key'] for column in table['columns'])
    row_ids = [new_row_id(), new_row_id()]

    # System columns are not filled in by the server: rows appended over the
    # websocket without '_ctime'/'_creator' keep those fields empty
    execute(websocket, {
        'op_type': 'append_rows',
        'table_id': table['_id'],
        'row_datas': [
            {'_id': row_ids[0], text_key: 'a', number_key: 1},
            {'_id': row_ids[1], text_key: 'b', number_key: 2},
        ],
    })

    rows = list_rows(base, table_name)

    assert [row['_id'] for row in rows] == row_ids
    assert [(row['text'], row['number']) for row in rows] == [('a', 1), ('b', 2)]
    assert snapshot_json(matcher=MATCHER) == normalize([row for row in rows if row['_id'] in row_ids])


def test_insert_row(base: Base, websocket: WebSocketClient, snapshot_json: SnapshotAssertion):
    table_name = 'test_insert_row'
    table, existing_row_ids = setup_table(base, table_name, [{'text': 'existing'}])
    row_id = new_row_id()

    execute(websocket, {
        'op_type': 'insert_row',
        'table_id': table['_id'],
        # 'row_id' is the row the new one is inserted below, its own ID comes from
        # the row data - without '_id' in there the new row ends up with '_id': None
        'row_id': existing_row_ids[0],
        'row_insert_position': 'insert_below',
        'row_data': {'_id': row_id, table['columns'][0]['key']: 'inserted'},
    })

    rows = list_rows(base, table_name)

    assert [row['_id'] for row in rows] == existing_row_ids + [row_id]
    assert rows[-1]['text'] == 'inserted'
    assert snapshot_json(matcher=MATCHER) == normalize(rows[-1])


