# Operations that change a column, and the column attributes they change. The
# server stores the column as it is sent, so 'new_column' has to be the complete
# column - sending only the changed attributes drops all the others.
COLUMN_OPERATIONS = [
    ('rename_column',
     lambda column: {
         'column_key': column['key'],
         'new_column_name': 'renamed',
         'old_column_name': column['name'],
     },
     {'name': 'renamed'}),
    ('resize_column',
     lambda column: {
         'column_key': column['key'],
         'new_column_width': 400,
         'old_column_width': column['width'],
     },
     {'width': 400}),
    ('freeze_column',
     lambda column: {'column_key': column['key'], 'frozen': True},
     {'frozen': True}),
    ('modify_column_type',
     lambda column: {
         'column_key': column['key'],
         'new_column': {**column, 'type': 'long-text', 'data': None},
         'old_column': column,
         'new_rows_data': [],
         'old_rows_data': [],
     },
     {'type': 'long-text'}),
]


@pytest.mark.parametrize('op_type, build_operation, expected',
                         COLUMN_OPERATIONS, ids=[operation[0] for operation in COLUMN_OPERATIONS])
def test_column_operation(base: Base, websocket: WebSocketClient, snapshot_json: SnapshotAssertion,
                          op_type: str, build_operation, expected: dict):
    table_name = f'test_column_operation_{op_type}'
    table, _ = setup_table(base, table_name)
    text_column = table['columns'][0]

    execute(websocket, {'op_type': op_type, 'table_id': table['_id'], **build_operation(text_column)})

    column = get_column(base, table_name, text_column['key'])

    for attribute, value in expected.items():
        assert column[attribute] == value

    assert snapshot_json(matcher=MATCHER) == normalize(column)


