"""Tests for the WebSocket API.

Clients do not only receive the changes of a base over socket.io, they also send
them: after joining the room of a base with a Base-Token, an operation is emitted
as 'update-dtable' and executed by dtable-server. The socket.io endpoint is served
by the API gateway under /api-gateway/socket.io and is not part of the OpenAPI
specs, so these tests use the client that ships with the seatable-api package.

Every test performs the operation over the websocket and verifies via the REST API
that the change was applied to the base.
"""

import base64
import json
import queue
import threading
import uuid

import pytest
import socketio
from conftest import BASE_URL, Base, base_operations_schema, normalize
from schemathesis import Case
from seatable_api import Base as SeaTableBase
from seatable_api.constants import JOIN_ROOM, UPDATE_DTABLE
from seatable_api.socket_io import SIO
from syrupy.assertion import SnapshotAssertion
from syrupy.matchers import path_type
from typing import Callable, Generator

from test_base_operations import create_table, append_rows


# Seconds to wait for an acknowledgement or an event
TIMEOUT = 10

COLUMNS = [
    {'column_name': 'text', 'column_type': 'text'},
    {'column_name': 'number', 'column_type': 'number'},
]

# Table, view and column IDs are generated by the server and differ on every run.
# Row IDs, timestamps and internal user names are replaced by conftest.normalize.
MATCHER = path_type({
    r'(.*\.)?(_id|key|.*_key)': (str,),
    r'(.*\.)?(hidden_columns|view_ids)\..*': (str,),
}, regex=True)


def new_row_id() -> str:
    """Row IDs of new rows are generated by the client, not by the server."""
    return base64.urlsafe_b64encode(uuid.uuid4().bytes).decode().rstrip('=')


class WebSocketClient:
    """socket.io client for a single base."""

    def __init__(self, api_token: str):
        # The seatable-api client resolves the socket.io URL and the Base-Token (JWT)
        seatable_base = SeaTableBase(api_token, BASE_URL)
        seatable_base.auth()

        self.dtable_uuid = seatable_base.dtable_uuid
        self.jwt_token = seatable_base.jwt_token
        self.url = f'{seatable_base.dtable_server_url}?dtable_uuid={self.dtable_uuid}'

        self.events = queue.Queue()
        self.disconnected = threading.Event()

        self.sio = SIO(reconnection=False, request_timeout=TIMEOUT)
        self.sio.on(UPDATE_DTABLE, lambda *args: self.events.put(json.loads(args[0])))
        self.sio.on('disconnect', lambda *args: self.disconnected.set())
        self.sio.on('io-disconnect', lambda *args: self.disconnected.set())

    def connect(self):
        self.sio.connect(self.url)

    def join_room(self, dtable_uuid: str = None, jwt_token: str = None) -> dict:
        """Emit 'join-room' and return the acknowledgement of the server."""
        return self.sio.call(
            JOIN_ROOM,
            (dtable_uuid or self.dtable_uuid, self.jwt_token if jwt_token is None else jwt_token),
            timeout=TIMEOUT,
        )

    def update_dtable(self, operation: dict) -> dict:
        """Emit 'update-dtable' and return the acknowledgement of the server."""
        ack = self.sio.call(UPDATE_DTABLE, (self.dtable_uuid, json.dumps(operation)), timeout=TIMEOUT)

        # Operations that update auto-numbers are acknowledged with the operation as second value
        return ack[0] if isinstance(ack, tuple) else ack

    def next_event(self) -> dict:
        """Return the next 'update-dtable' event that was broadcast to this client."""
        try:
            return self.events.get(timeout=TIMEOUT)
        except queue.Empty:
            pytest.fail(f'No {UPDATE_DTABLE} event received within {TIMEOUT} seconds')

    def disconnect(self):
        self.sio.disconnect()


def connect(api_token: str) -> WebSocketClient:
    """Return a client that has joined the room of the base of the API-Token."""
    client = WebSocketClient(api_token)
    client.connect()

    assert client.join_room()['status'] == 1

    return client


@pytest.fixture
def websocket_client(base: Base) -> Generator[Callable[[], WebSocketClient], None, None]:
    """Factory for clients that have joined the room of the test base."""
    clients = []

    def _connect() -> WebSocketClient:
        client = connect(base.api_token)
        clients.append(client)
        return client

    yield _connect

    for client in clients:
        client.disconnect()


@pytest.fixture
def websocket(websocket_client) -> WebSocketClient:
    return websocket_client()


def execute(client: WebSocketClient, operation: dict) -> dict:
    """Execute an operation over the websocket and assert that it was applied."""
    ack = client.update_dtable(operation)

    assert ack['status'] == 1, ack
    assert ack['message'] == 'Update completed'
    assert isinstance(ack['dtable_version'], int)

    return ack


def call(base: Base, operation_id: str, body: dict = None, query: dict = None, **path_parameters):
    """Call a base operation with the Base-Token of the test base."""
    arguments = {
        'path_parameters': {'base_uuid': base.uuid, **path_parameters},
        'headers': {'Authorization': f'Bearer {base.token}'},
    }
    if body is not None:
        arguments['body'] = body
    if query is not None:
        arguments['query'] = query

    case: Case = base_operations_schema.find_operation_by_id(operation_id).Case(**arguments)
    response = case.call()

    assert response.status_code == 200

    return response


def get_table(base: Base, table_name: str) -> dict:
    """Return the metadata of a table, which contains the IDs that operations need."""
    response = call(base, 'getMetadata')
    return next(table for table in response.json()['metadata']['tables'] if table['name'] == table_name)


def list_rows(base: Base, table_name: str) -> list[dict]:
    response = call(base, 'listRows', query={'table_name': table_name, 'convert_keys': True})
    return response.json()['rows']


def get_column(base: Base, table_name: str, column_key: str) -> dict:
    response = call(base, 'listColumns', query={'table_name': table_name})
    return next((column for column in response.json()['columns'] if column['key'] == column_key), None)


def get_view(base: Base, table_name: str, view_id: str) -> dict:
    """Look the view up by ID, because operations may change its name."""
    response = call(base, 'listViews', query={'table_name': table_name})
    return next((view for view in response.json()['views'] if view['_id'] == view_id), None)


def setup_table(base: Base, table_name: str, rows: list[dict] = None) -> tuple[dict, list[str]]:
    """Create a table via REST and return its metadata and the IDs of its rows."""
    create_table(base, table_name, COLUMNS)
    row_ids = append_rows(base, table_name, rows) if rows else []

    return get_table(base, table_name), row_ids


def test_join_room(base: Base):
    client = WebSocketClient(base.api_token)
    client.connect()

    ack = client.join_room()

    assert ack['status'] == 1
    assert ack['message'] == 'Joined successfully'
    assert isinstance(ack['dtable_version'], int)
    assert client.sio.transport() == 'websocket'

    client.disconnect()


def test_join_room_with_invalid_token(base: Base):
    client = WebSocketClient(base.api_token)
    client.connect()

    ack = client.join_room(jwt_token='not-a-base-token')

    assert ack['status'] == 0
    assert ack['error_type'] == 'token_expired'
    assert ack['message'] == 'Token expired'

    # The server closes the connection after a rejected join
    assert client.disconnected.wait(timeout=TIMEOUT)


def test_join_room_with_unknown_base(base: Base):
    client = WebSocketClient(base.api_token)
    client.connect()

    ack = client.join_room(dtable_uuid='00000000-0000-0000-0000-000000000000')

    assert ack['status'] == 0
    assert ack['error_type'] == 'permission_denied'
    assert ack['message'] == 'Permission denied'

    assert client.disconnected.wait(timeout=TIMEOUT)


